"""ChatStat — Oracle `HBT_CHAT_STAT` 한 행: 질문 하나를 처리한 **통계**(질문·답변 내용은 담지 않는다).

AI_STORE_STATS=true 일 때만 쌓인다. 집계용(하루 질문 수, 문서/LLM 답 비율, 응답 시간)이라 개인정보가 없다.
"""
from __future__ import annotations

from dataclasses import dataclass

TABLE = "HBT_CHAT_STAT"

DDL = (
    """CREATE TABLE HBT_CHAT_STAT (
        id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        answer_mode     VARCHAR2(10) NOT NULL,   -- mode 는 Oracle 예약어라 쓸 수 없다
        ai              VARCHAR2(3)  NOT NULL,
        provider        VARCHAR2(20) NOT NULL,
        question_len    NUMBER(5)    NOT NULL,
        source_count    NUMBER(3)    NOT NULL,
        character_count NUMBER(3)    NOT NULL,
        latency_ms      NUMBER(8)    NOT NULL
    )""",
    "CREATE INDEX HBT_CHAT_STAT_CREATED_IX ON HBT_CHAT_STAT (created_at)",
)


@dataclass(frozen=True)
class ChatStat:
    mode: str            # llm | fallback | fixed
    ai: str              # on | off
    provider: str        # ollama | anthropic | none
    question_len: int
    source_count: int
    character_count: int
    latency_ms: int
