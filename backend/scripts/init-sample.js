// Oracle 샘플 테이블(HBT_SAMPLE) 준비 — 여러 번 실행해도 안전하다.
// 사용: cd backend && node scripts/init-sample.js   (backend/.env 의 ORACLE_* 사용)
const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '..', '.env') });
const { query, closePool } = require('../db');

const CREATE_SQL = `
  CREATE TABLE HBT_SAMPLE (
    ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME       VARCHAR2(50)  NOT NULL,
    NOTE       VARCHAR2(200),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
  )`;

async function main() {
  try {
    await query(CREATE_SQL);
    console.log('HBT_SAMPLE 테이블 생성');
  } catch (err) {
    if (err.errorNum === 955) console.log('HBT_SAMPLE 테이블 이미 있음');
    else throw err;
  }

  const { rows } = await query('SELECT COUNT(*) AS CNT FROM HBT_SAMPLE');
  if (rows[0].CNT === 0) {
    const samples = [
      { name: '샘플 1', note: 'Oracle Autonomous DB 연결 확인용 예시 행' },
      { name: '샘플 2', note: 'POST /api/db-sample 로 행을 더 넣을 수 있다' },
    ];
    for (const s of samples) {
      await query('INSERT INTO HBT_SAMPLE (NAME, NOTE) VALUES (:name, :note)', s);
    }
    console.log(`예시 행 ${samples.length}개 삽입`);
  } else {
    console.log(`기존 행 ${rows[0].CNT}개 — 삽입 생략`);
  }
}

main()
  .then(() => closePool())
  .catch(async (err) => {
    // 비밀값이 섞일 수 있는 전체 메시지 대신 오류 코드만 출력
    console.error('init-sample 실패:', err.code || err.errorNum || err.name);
    await closePool().catch(() => {});
    process.exitCode = 1;
  });
