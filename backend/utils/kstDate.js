/* ====================================================================
 * 한국 표준시(KST, UTC+9) 날짜 문자열 유틸
 * ------------------------------------------------------------------
 * Render 등 UTC 서버 환경에서 한국 시간 기준 날짜 문자열을 만들기 위한 유틸.
 * new Date().toISOString() 을 그대로 쓰면 KST 오전 9시 이전에 날짜가 하루 밀린다
 * (예: 한국 시각 9/3 08:00은 UTC로는 아직 9/2 23:00이라 "9/2"로 잘못 찍힘).
 * 행운 뽑기 기능의 "오늘 하루 참여 여부/이력" 판단이 이 함수의 날짜 경계를
 * 기준으로 리셋되므로, 서버가 어느 시간대에서 돌아가든 자정 KST를 기준으로
 * "오늘"이 바뀌도록 여기서 보정한다.
 * ==================================================================== */
// date의 UTC 타임스탬프에 9시간을 더해 KST 시각으로 만든 뒤, ISO 문자열의
// 앞 10자리(YYYY-MM-DD)만 잘라 반환한다. Date 객체 자체는 여전히 UTC 기준으로
// 동작하지만, 9시간을 더한 상태에서 slice(0,10)을 하면 결과적으로 "KST 달력상 날짜"가 나온다.
function getKstDateString(date = new Date()) {
  const kst = new Date(date.getTime() + 9 * 60 * 60 * 1000);
  return kst.toISOString().slice(0, 10);
}

module.exports = { getKstDateString };
